def check_order(size, quantity, stock):
    # 1. Ромб «Размер выбран?» (Ветка "Нет" -> Ошибка)
    if size is None:
        return "Ошибка: выберите размер"
        
    # 2. Ромб «Количество > 0?» (Ветка "Нет" -> Ошибка)
    if quantity <= 0:
        return "Ошибка: количество должно быть > 0"
        
    # 3. Ромб «Количество ≤ остаток?» (Ветка "Нет" -> Ошибка)
    if quantity > stock:
        return "Ошибка: недостаточно на складе"
        
    # Прямоугольник «Добавить в заказ» (Ветка "Да" -> Успех)
    return "Можно добавить в заказ"

# Проверочный запуск функции для тестирования всех веток блок-схемы
if __name__ == "__main__":
    current_stock = 15  # Доступный остаток игрушек на складе
    print(f"Текущий остаток товара на складе: {current_stock} шт.\n")
    
    # Тест 1: Размер не выбран (size = None)
    print("Тест 1 (Размер не выбран):")
    print(f"Результат: {check_order(None, 5, current_stock)}\n")
    
    # Тест 2: Некорректное количество (quantity = 0)
    print("Тест 2 (Количество <= 0):")
    print(f"Результат: {check_order('Большой', 0, current_stock)}\n")
    
    # Тест 3: Превышение остатка склада (quantity = 20 при наличии 15)
    print("Тест 3 (Количество > остатка):")
    print(f"Результат: {check_order('Большой', 20, current_stock)}\n")
    
    # Тест 4: Все проверки пройдены успешно (Размер задан, 5 шт. <= 15 шт.)
    print("Тест 4 (Успешное прохождение всех проверок):")
    print(f"Результат: {check_order('Большой', 5, current_stock)}\n")
